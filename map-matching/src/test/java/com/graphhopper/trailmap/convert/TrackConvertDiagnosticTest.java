            System.out.println("  edge_id  | snapDist | emCost  | road_class      | road_env      | gravelPrio | gScaleNum | wgt/m  | chosen");
            System.out.println("  ---------|----------|---------|-----------------|---------------|------------|-----------|--------|-------");
