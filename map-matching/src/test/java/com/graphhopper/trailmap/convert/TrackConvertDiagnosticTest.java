    /** Resolve the concrete enum Class backing an EnumEncodedValue, so we can call get(). */
    @SuppressWarnings("unchecked")
    private static Class<? extends Enum> enumClass(EncodingManager em, String key) {
        // road_class -> com.graphhopper.routing.ev.RoadClass, road_environment -> RoadEnvironment
        try {
            String simple = "";
            for (String part : key.split("_")) {
                simple += Character.toUpperCase(part.charAt(0)) + part.substring(1);
            }
            return (Class<? extends Enum>) Class.forName("com.graphhopper.routing.ev." + simple);
        } catch (ClassNotFoundException e) {
            throw new IllegalStateException("No enum class for EV " + key, e);
        }
    }

    // ----------------------------------------------------------------------
    // LEG EDGE DUMP: for a single leg obs[fromObs] -> obs[toObs], list the
    // matcher's edge slice AND the gravel /route edge sequence between the two
    // snaps, edge-by-edge, with length, base->adj nodes (+coords), road_class,
    // gravel base priority, and the gravel weight in BOTH directions (so a
    // one-way edge shows up as one direction = INF). Then print the set
    // difference: which edges /route used that the matcher skipped, and vice
    // versa. This is the analytic tool for "matcher edges != /route edges".
    //
    // Usage:
    //   -Dtest=TrackConvertDiagnosticTest#dumpLegEdges
    //   -Dconvert.gpx=/abs/path.gpx -Dconvert.profile=gravel
    //   -Dconvert.gpsAccuracy=20 -Dconvert.fromObs=10 -Dconvert.toObs=11
    // ----------------------------------------------------------------------
    @Test
    void dumpLegEdges() throws Exception {
        String gpxPath = System.getProperty("convert.gpx");
        Assumptions.assumeTrue(gpxPath != null,
                "Pass -Dconvert.gpx=/abs/path/to/file.gpx to run this test");
        String profileName = System.getProperty("convert.profile", "gravel");
        double gpsAccuracy = Double.parseDouble(System.getProperty("convert.gpsAccuracy", "10"));
        int fromObs = Integer.parseInt(System.getProperty("convert.fromObs"));
        int toObs = Integer.parseInt(System.getProperty("convert.toObs"));

        List<Observation> observations = parseGpx(new File(gpxPath));
        // Match the compareSegmentationV1V2 pipeline so obs indices line up: optional densify,
        // and optional adaptive-σ fork (with the same client levers) instead of plain matching.
        String densifyProp = System.getProperty("convert.densifyMaxGap");
        if (densifyProp != null) {
            observations = com.graphhopper.trailmap.matching.ObservationDensifier.densify(
                    observations, Double.parseDouble(densifyProp));
        }
        PMap hints = new PMap();
        hints.putObject("profile", profileName);
        MatchResult mr;
        if ("true".equals(System.getProperty("convert.adaptiveSigma"))
                || "true".equals(System.getProperty("convert.autoSigma"))) {
            MatcherConfig cfg = new MatcherConfig();
            cfg.autoSigma = "true".equals(System.getProperty("convert.autoSigma"));
            cfg.adaptiveSigma = "true".equals(System.getProperty("convert.adaptiveSigma"));
            cfg.autoSigmaMaxM = Double.parseDouble(
                    System.getProperty("convert.autoSigmaMax", String.valueOf(cfg.autoSigmaMaxM)));
            String crm = System.getProperty("convert.candRadiusMult");
            if (crm != null) cfg.candidateRadiusSigmaMult = Double.parseDouble(crm);
            String lam = System.getProperty("convert.lambda");
            if (lam != null) cfg.emissionDesirabilityLambda = Double.parseDouble(lam);
            String beta = System.getProperty("convert.beta");
            if (beta != null) cfg.transitionProbabilityBeta = Double.parseDouble(beta);
            TrailmapMapMatching fork = TrailmapMapMatching.fromGraphHopper(hopper, hints, cfg);
            mr = fork.match(observations);
        } else {
            MapMatching matching = MapMatching.fromGraphHopper(hopper, hints);
            matching.setMeasurementErrorSigma(gpsAccuracy);
            mr = matching.match(observations);
        }
        List<Tracepoint> tps = mr.getTracepoints();
        List<EdgeMatch> ems = mr.getEdgeMatches();

        // obs -> em forward scan (same as diagnoseProbes)
        int n = tps.size();
        int[] obsToEm = new int[n];
        for (int i = 0; i < n; i++) obsToEm[i] = -1;
        int searchFrom = 0;
        for (int i = 0; i < n; i++) {
            Tracepoint tp = tps.get(i);
            if (!tp.isMatched() || tp.getEdgeId() == null) continue;
            int target = tp.getEdgeId();
            int found = -1;
            for (int j = searchFrom; j < ems.size(); j++)
                if (ems.get(j).getEdgeState().getEdge() == target) { found = j; break; }
            if (found < 0)
                for (int j = searchFrom - 1; j >= 0; j--)
                    if (ems.get(j).getEdgeState().getEdge() == target) { found = j; break; }
            if (found >= 0) { obsToEm[i] = found; searchFrom = found; }
        }

        EncodingManager enc = hopper.getEncodingManager();
        EnumEncodedValue<?> rcEv = enc.hasEncodedValue("road_class")
                ? enc.getEnumEncodedValue("road_class", enumClass(enc, "road_class")) : null;
        DecimalEncodedValue gpEv = enc.hasEncodedValue("gravel_base_priority")
                ? enc.getDecimalEncodedValue("gravel_base_priority") : null;
        Weighting w = null;
        Profile prof = hopper.getProfile(profileName);
        if (prof != null) {
            try { w = hopper.createWeighting(prof, new PMap()); }
            catch (Exception ex) { System.out.println("(no weighting: " + ex.getMessage() + ")"); }
        }

        System.out.println("=== INPUT ===");
        System.out.println("gpx=" + gpxPath + " profile=" + profileName + " sigma=" + gpsAccuracy);
        System.out.printf("leg obs[%d]->obs[%d]  snapDist %s / %s%n", fromObs, toObs,
                tps.get(fromObs).getDistance(), tps.get(toObs).getDistance());

        int emFrom = obsToEm[fromObs], emTo = obsToEm[toObs];
        System.out.println();
        System.out.printf("=== MATCHER SLICE  em[%d..%d]  (obs[%d]->obs[%d]) ===%n", emFrom, emTo, fromObs, toObs);
        System.out.println("legend: gravelW fwd/rev = gravel routing weight in base->adj / adj->base; INF = not traversable that way (one-way)");
        java.util.LinkedHashSet<Integer> matcherIds = new java.util.LinkedHashSet<>();
        if (emFrom >= 0 && emTo >= 0) {
            for (int e = Math.min(emFrom, emTo); e <= Math.max(emFrom, emTo); e++) {
                EdgeIteratorState st = ems.get(e).getEdgeState();
                matcherIds.add(st.getEdge());
                printLegEdge("  ", st, w, rcEv, gpEv);
            }
        }

        GHPoint a = tps.get(fromObs).getSnappedPoint();
        GHPoint b = tps.get(toObs).getSnappedPoint();
        GHRequest req = new GHRequest(a, b);
        req.setProfile(profileName);
        req.setPathDetails(List.of("edge_id"));
        req.putHint("instructions", false);
        req.putHint("calc_points", true);
        GHResponse rsp = hopper.route(req);
        System.out.println();
        System.out.printf("=== /route(snap[%d], snap[%d])  dist=%.1fm ===%n",
                fromObs, toObs, rsp.hasErrors() ? -1.0 : rsp.getBest().getDistance());
        java.util.LinkedHashSet<Integer> routeIds = new java.util.LinkedHashSet<>();
        if (!rsp.hasErrors()) {
            List<PathDetail> det = rsp.getBest().getPathDetails().get("edge_id");
            int prev = Integer.MIN_VALUE;
            for (PathDetail d : det) {
                int id = ((Number) d.getValue()).intValue();
                if (id != prev) {
                    EdgeIteratorState st = hopper.getBaseGraph().getEdgeIteratorState(id, Integer.MIN_VALUE);
                    printLegEdge("  ", st, w, rcEv, gpEv);
                    routeIds.add(id);
                    prev = id;
                }
            }
        } else {
            System.out.println("  ROUTE ERROR: " + rsp.getErrors());
        }

        java.util.LinkedHashSet<Integer> onlyRoute = new java.util.LinkedHashSet<>(routeIds);
        onlyRoute.removeAll(matcherIds);
        java.util.LinkedHashSet<Integer> onlyMatcher = new java.util.LinkedHashSet<>(matcherIds);
        onlyMatcher.removeAll(routeIds);
        System.out.println();
        System.out.println("edges in /route NOT in matcher slice (matcher skipped these): " + onlyRoute);
        System.out.println("edges in matcher slice NOT in /route (route skipped these):   " + onlyMatcher);
    }

    private void printLegEdge(String pre, EdgeIteratorState st, Weighting w,
                              EnumEncodedValue<?> rcEv, DecimalEncodedValue gpEv) {
        int id = st.getEdge();
        double len = st.getDistance();
        PointList g = st.fetchWayGeometry(FetchMode.ALL);
        double blat = g.getLat(0), blon = g.getLon(0);
        double alat = g.getLat(g.size() - 1), alon = g.getLon(g.size() - 1);
        String rc = rcEv != null ? st.get(rcEv).toString() : "?";
        String gp = gpEv != null ? String.format("%.3f", st.get(gpEv)) : "?";
        String fwd = "?", rev = "?";
        if (w != null) {
            try { double f = w.calcEdgeWeight(st, false); fwd = Double.isInfinite(f) ? "INF" : String.format("%.2f", f); }
            catch (Exception e) { fwd = "err"; }
            try { double r = w.calcEdgeWeight(st, true); rev = Double.isInfinite(r) ? "INF" : String.format("%.2f", r); }
            catch (Exception e) { rev = "err"; }
        }
        System.out.printf("%sedge=%-8d %7d->%-7d len=%6.1fm rc=%-12s gPrio=%-6s gravelW fwd=%-7s rev=%-7s base=(%.6f,%.6f) adj=(%.6f,%.6f)%n",
                pre, id, st.getBaseNode(), st.getAdjNode(), len, rc, gp, fwd, rev, blat, blon, alat, alon);
    }

