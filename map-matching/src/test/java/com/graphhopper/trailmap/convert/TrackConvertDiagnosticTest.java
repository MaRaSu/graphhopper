    // sbc_keha_g.gpx (gravel, auto-sigma, M1 radius=3, densify 40m, β=4,
    // λ=1, segmentation v2, optimizer kept-obs-only) N times in one JVM.
    // Discards the first 2 runs (JIT warmup), then reports median of the
    // warm runs. Also runs with β=2 for comparison.
    //
    // Stage breakdown tracked:
    //   1. densify
    //   2. match (probe pass vs final pass; candidateSearch vs Viterbi)
    //   3. segment (including phantom-detour /route calls)
    //   4. optimize (probe /route calls counted + timed)
    //
    // No production behavior change — only System.nanoTime() wrappers and
    // an instrumented GraphHopper subclass that counts route() calls.
    // -----------------------------------------------------------------------

    /**
     * Pipeline performance breakdown for sbc_keha_g.gpx with the client's production config.
     *
     * <p>Behavior-preserving: no algorithm changes. Timing hooks are additive to the
     * matcher's existing {@code statistics} map. New keys added to statistics:
     * {@code matchProbePassNs}, {@code matchFinalPassNs}, {@code candidateSearchNs},
     * {@code viterbiNs}. These are read here at test time — no other caller reads them.
     *
     * <p>The converter's own stage timing (already in {@code ConvertTrackResponse.Stats}:
     * {@code matchingMs} = segmentation time, {@code optimizationMs} = optimization time)
     * is used directly — no modifications to converter code.
     *
     * <p>Runs 7 iterations per beta value in one JVM. Discards the first 2 (JIT warmup).
     * Reports median of warm runs plus cold vs warm delta.
     *
     * <p>Run: {@code MAVEN_OPTS="-Xmx16g" mvn -f .../graphhopper/pom.xml -pl map-matching
     *   test -Dtest=TrackConvertDiagnosticTest#perfBreakdown -Dsurefire.useFile=false}
     */
    @Test
    void perfBreakdown() throws Exception {
        // --- Fixed config mirrors the user's production request for sbc_keha_g ---
        final String GPX_PATH = "../../data/gpx-for-testing/sbc_keha_g.gpx";
        final String PROFILE = "gravel";
        final double GPS_ACCURACY_M = 20.0;       // auto-sigma seed (cm_auto_sigma=true)
        final double DENSIFY_GAP_M = 40.0;        // cm_densify_max_gap_m
        final double CAND_RADIUS_MULT = 3.0;      // cm_candidate_radius_sigma_mult
        final double AUTO_SIGMA_MAX_M = 10.0;     // cm_auto_sigma_max_m
        final double AUTO_SIGMA_PERCENTILE = 0.9; // cm_auto_sigma_percentile (default)
        final double LAMBDA = 1.0;                // cm_emission_desirability_lambda
        final boolean SEGMENTATION_V2 = true;     // cm_segmentation_v2
        final boolean KEPT_OBS_ONLY = true;       // cm_optimizer_kept_obs_only
        final double MIN_ROUTED_SEGMENT_M = 40.0; // min_routed_segment_m
        final double SIMPLIFY_EPS_M = 3.0;        // coordinates_simplify_eps

        final int TOTAL_RUNS = 7;
        final int DISCARD = 2; // JIT warmup

        File gpxFile = new File(GPX_PATH);
        Assumptions.assumeTrue(gpxFile.exists(),
                "sbc_keha_g.gpx not found at " + gpxFile.getAbsolutePath() + " — skipping");

        List<Observation> rawObs = parseGpx(gpxFile);
        System.out.printf("%n=== PERF BREAKDOWN: %s (%d raw points) ===%n",
                gpxFile.getName(), rawObs.size());
        System.out.println("Config: profile=" + PROFILE
                + " autoSigma=true(seed=" + GPS_ACCURACY_M
                + " max=" + AUTO_SIGMA_MAX_M + " p=" + AUTO_SIGMA_PERCENTILE + ")"
                + " M1_mult=" + CAND_RADIUS_MULT
                + " densify=" + DENSIFY_GAP_M + "m"
                + " lambda=" + LAMBDA
                + " segV2=" + SEGMENTATION_V2
                + " keptObsOnly=" + KEPT_OBS_ONLY
                + " minRouted=" + MIN_ROUTED_SEGMENT_M + "m");
        System.out.println("Runs: " + TOTAL_RUNS + " total, discard first "
                + DISCARD + " (JIT warmup), report median of warm runs");

        // Run for both beta values the user cares about (cm_beta=2 default, cm_beta=4 test)
        for (double beta : new double[]{2.0, 4.0}) {
            System.out.printf("%n--- beta=%.0f ---%n", beta);

            // Per-run measurements (index 0 = first run, cold)
            long[] tDensifyNs = new long[TOTAL_RUNS];
            long[] tProbeNs   = new long[TOTAL_RUNS]; // matcher probe pass
            long[] tFinalNs   = new long[TOTAL_RUNS]; // matcher final pass
            long[] tCandNs    = new long[TOTAL_RUNS]; // candidateSearch within final pass
            long[] tViterbiNs = new long[TOTAL_RUNS]; // Viterbi within final pass
            long[] tSegNs     = new long[TOTAL_RUNS]; // segmentation stage (from converter stats)
            long[] tOptNs     = new long[TOTAL_RUNS]; // optimization stage (from converter stats)
            int[]  nObs       = new int[TOTAL_RUNS];  // densified observation count
            long[] nCandPairs = new long[TOTAL_RUNS]; // Viterbi inner-loop work proxy
            int[]  nRegions   = new int[TOTAL_RUNS];  // number of matched+coords regions
            int[]  nWaypoints = new int[TOTAL_RUNS];  // optimizer output waypoints

            for (int run = 0; run < TOTAL_RUNS; run++) {

                // Stage 1: densify
                long t0 = System.nanoTime();
                List<Observation> obs = com.graphhopper.trailmap.matching.ObservationDensifier.densify(
                        new ArrayList<>(rawObs), DENSIFY_GAP_M);
                tDensifyNs[run] = System.nanoTime() - t0;
                nObs[run] = obs.size();

                // Stage 2: match (probe pass + final pass via TrailmapMapMatching)
                PMap hints = new PMap();
                hints.putObject("profile", PROFILE);
                MatcherConfig cfg = new MatcherConfig();
                cfg.measurementErrorSigma = GPS_ACCURACY_M;
                cfg.autoSigma = true;
                cfg.autoSigmaSeedM = GPS_ACCURACY_M;
                cfg.autoSigmaMaxM = AUTO_SIGMA_MAX_M;
                cfg.autoSigmaPercentile = AUTO_SIGMA_PERCENTILE;
                cfg.candidateRadiusSigmaMult = CAND_RADIUS_MULT;
                cfg.emissionDesirabilityLambda = LAMBDA;
                cfg.transitionProbabilityBeta = beta;

                TrailmapMapMatching matcher =
                        TrailmapMapMatching.fromGraphHopper(hopper, hints, cfg);
                com.graphhopper.matching.MatchResult mr =
                        matcher.match(new ArrayList<>(obs));

                Map<String, Object> mStats = matcher.getStatistics();
                tProbeNs[run]   = longStat(mStats, "matchProbePassNs");
                tFinalNs[run]   = longStat(mStats, "matchFinalPassNs");
                tCandNs[run]    = longStat(mStats, "candidateSearchNs");
                tViterbiNs[run] = longStat(mStats, "viterbiNs");

                // Candidate pairs: Σ snaps[i] × snaps[i+1] (Viterbi inner loop cost proxy)
                int[] snapsPerObs = (mStats.get("snapsPerObservation") instanceof int[])
                        ? (int[]) mStats.get("snapsPerObservation") : new int[0];
                long pairs = 0;
                for (int i = 0; i + 1 < snapsPerObs.length; i++) {
                    pairs += (long) snapsPerObs[i] * snapsPerObs[i + 1];
                }
                nCandPairs[run] = pairs;

                // Stages 3 + 4: segment + optimize (converter records each in response stats)
                // NOTE: ConvertTrackResponse.Stats.matchingMs = tSegmented-t0 (segmentation)
                //        ConvertTrackResponse.Stats.optimizationMs = tOptimized-tSegmented (optimization)
                // Both are already computed inside TrackToRouteConverter.buildResponse().
                double estSigma = ((Number) mStats.get("autoSigmaEstimatedM")).doubleValue();
                double snapThresholdM =
                        TrackToRouteConverter.AUTO_SIGMA_SNAP_THRESHOLD_MULT * estSigma;
                double driftFloorM =
                        TrackToRouteConverter.AUTO_SIGMA_DRIFT_FLOOR_MULT * estSigma;

                TrackToRouteConverter conv = new TrackToRouteConverter(hopper);
                conv.setSegmentationV2Enabled(SEGMENTATION_V2);
                conv.setOptimizerKeptObsOnly(KEPT_OBS_ONLY);

                ConvertTrackResponse rsp = conv.convert(
                        mr, new ArrayList<>(obs), PROFILE, null,
                        snapThresholdM, MIN_ROUTED_SEGMENT_M, SIMPLIFY_EPS_M,
                        TrackToRouteConverter.DEFAULT_MIN_DETOUR_M,
                        TrackToRouteConverter.DEFAULT_MAX_DETOUR_RATIO,
                        driftFloorM, false);

                // Converter's own stage timings (ms → ns for uniform units)
                ConvertTrackResponse.Stats rspStats = rsp.getStats();
                tSegNs[run] = rspStats.matchingMs * 1_000_000L;
                tOptNs[run] = rspStats.optimizationMs * 1_000_000L;
                nRegions[run] = rspStats.routedSegments + rspStats.coordinatesSegments;
                nWaypoints[run] = rsp.getWaypoints() != null ? rsp.getWaypoints().size() : 0;
            }

            // Compute medians of warm runs
            int warmCount = TOTAL_RUNS - DISCARD;
            long medDensify = median(tDensifyNs, DISCARD, TOTAL_RUNS);
            long medProbe   = median(tProbeNs,   DISCARD, TOTAL_RUNS);
            long medFinal   = median(tFinalNs,   DISCARD, TOTAL_RUNS);
            long medCand    = median(tCandNs,    DISCARD, TOTAL_RUNS);
            long medViterbi = median(tViterbiNs, DISCARD, TOTAL_RUNS);
            long medSeg     = median(tSegNs,     DISCARD, TOTAL_RUNS);
            long medOpt     = median(tOptNs,     DISCARD, TOTAL_RUNS);

            int  medObs     = (int) medianInt(nObs,      DISCARD, TOTAL_RUNS);
            long medCandP   = median(nCandPairs,         DISCARD, TOTAL_RUNS);
            int  medRegions = (int) medianInt(nRegions,  DISCARD, TOTAL_RUNS);
            int  medWps     = (int) medianInt(nWaypoints,DISCARD, TOTAL_RUNS);

            long medMatch = medProbe + medFinal;
            long medTotal = medDensify + medMatch + medSeg + medOpt;

            System.out.printf("  Warm runs (N=%d): densified_obs=%d  candPairs(final_pass)=%d"
                    + "  regions=%d  waypoints=%d%n",
                    warmCount, medObs, medCandP, medRegions, medWps);
            System.out.println();
            System.out.printf("  %-32s  %8s  %6s%n", "Stage", "ms", "% total");
            System.out.println("  " + "-".repeat(52));
            printRow("densify", medDensify, medTotal);
            System.out.printf("  %-32s  %8.1f  %5.1f%%%n",
                    "match (total)", ns2ms(medMatch), pct(medMatch, medTotal));
            printRow("  probe pass (auto-sigma)", medProbe, medTotal);
            printRow("  final pass", medFinal, medTotal);
            printRow("    candidateSearch", medCand, medTotal);
            printRow("    viterbi (calcPaths)", medViterbi, medTotal);
            printRow("segment", medSeg, medTotal);
            printRow("optimize", medOpt, medTotal);
            System.out.println("  " + "-".repeat(52));
            System.out.printf("  %-32s  %8.1f%n", "TOTAL (warm median ms)", ns2ms(medTotal));
            System.out.println();

            // Cold vs warm delta (JIT effect visibility)
            long coldMatch = (tProbeNs[0] + tFinalNs[0]);
            long coldSeg   = tSegNs[0];
            long coldOpt   = tOptNs[0];
            System.out.printf("  Cold(run1) vs warm(median): match=%dms/%.1fms"
                    + "  seg=%dms/%.1fms  opt=%dms/%.1fms%n",
                    coldMatch / 1_000_000, ns2ms(medMatch),
                    coldSeg   / 1_000_000, ns2ms(medSeg),
                    coldOpt   / 1_000_000, ns2ms(medOpt));
        }

        assertTrue(true, "perfBreakdown completed");
    }

    private static long longStat(Map<String, Object> stats, String key) {
        Object v = stats.get(key);
        if (v instanceof Long) return (Long) v;
        if (v instanceof Number) return ((Number) v).longValue();
        return 0L;
    }

    private static double ns2ms(long ns) { return ns / 1_000_000.0; }

    private static double pct(long part, long total) {
        return total == 0 ? 0.0 : 100.0 * part / total;
    }

    private static void printRow(String label, long ns, long total) {
        System.out.printf("  %-32s  %8.1f  %5.1f%%%n", label, ns2ms(ns), pct(ns, total));
    }

    /** Median of arr[from..to) (nanoseconds). */
    private static long median(long[] arr, int from, int to) {
        int n = to - from;
        if (n <= 0) return 0;
        long[] sub = Arrays.copyOfRange(arr, from, to);
        Arrays.sort(sub);
        return (n % 2 == 1) ? sub[n / 2] : (sub[n / 2 - 1] + sub[n / 2]) / 2;
    }

    /** Median of int[] arr[from..to) returned as long. */
    private static long medianInt(int[] arr, int from, int to) {
        int n = to - from;
        if (n <= 0) return 0;
        int[] sub = Arrays.copyOfRange(arr, from, to);
        Arrays.sort(sub);
        return (n % 2 == 1) ? sub[n / 2] : (sub[n / 2 - 1] + sub[n / 2]) / 2L;
    }

    /** Scan the RAW (un-densified) input GPX for consecutive coincident points — to verify whether
     *  duplicates are in the source data (not created by densification).
     *  -Dconvert.gpx=... [-Dconvert.coincidentEps=2.0] */
    @Test
    void findCoincidentInputPoints() throws Exception {
        String gpxPath = System.getProperty("convert.gpx");
        Assumptions.assumeTrue(gpxPath != null, "Pass -Dconvert.gpx=/abs/path.gpx");
        List<Observation> raw = parseGpx(new File(gpxPath));
        double eps = Double.parseDouble(System.getProperty("convert.coincidentEps", "2.0"));
        System.out.println("=== RAW input coincidence scan: " + new File(gpxPath).getName()
                + " (" + raw.size() + " points, eps=" + eps + "m) ===");
        int dup = 0;
        for (int i = 1; i < raw.size(); i++) {
            GHPoint a = raw.get(i - 1).getPoint();
            GHPoint b = raw.get(i).getPoint();
            double d = DistanceCalcEarth.DIST_EARTH.calcDist(a.lat, a.lon, b.lat, b.lon);
            if (d < eps) {
                dup++;
                System.out.printf("  raw[%d]=(%.7f, %.7f)  raw[%d]=(%.7f, %.7f)  gap=%.3fm%n",
                        i - 1, a.lat, a.lon, i, b.lat, b.lon, d);
            }
        }
        System.out.println("Total consecutive coincident pairs (<" + eps + "m): " + dup);
    }

    /** Print the per-observation v2 signals over a window so we can SEE the shape that drives
     *  the coords decision (snap rise/fall, edge contiguity, transition length, emHigh/offGrid).
     *  Reads RegionSegmenter's package-private v2 constants directly (same package). */
    private static void dumpV2Signals(MatchResult mr, int from, int to, double snapThreshold,
                                      Map<String, Object> matcherStats) {
        List<Tracepoint> tps = mr.getTracepoints();
        if (tps == null) return;
        int n = tps.size();
        double[] snap = new double[n];
        for (int i = 0; i < n; i++) {
            Tracepoint tp = tps.get(i);
            Double d = tp.isMatched() ? tp.getDistance() : null;
            snap[i] = (d == null) ? Double.NaN : d;
        }
        // Adaptive-σ diagnostics, indexed by ORIGINAL observation (pre-filter); align to tracepoints
        // by original-index where available, else fall back to positional.
        double[] sigmaPerObs = matcherStats != null && matcherStats.get("adaptiveSigmaPerObs") instanceof double[]
                ? (double[]) matcherStats.get("adaptiveSigmaPerObs") : null;
        double[] prePassSnap = matcherStats != null && matcherStats.get("adaptiveSnapPrePass") instanceof double[]
                ? (double[]) matcherStats.get("adaptiveSnapPrePass") : null;
        from = Math.max(0, from);
        to = Math.min(n - 1, to);
        System.out.printf("=== v2 signal dump obs[%d..%d]  snapThreshold=%.1f, offGrid-seed-min-run=%d%s ===%n",
                from, to, snapThreshold, RegionSegmenter.V2_OFFGRID_SEED_MIN_RUN,
                sigmaPerObs != null ? "  [adaptiveσ]" : "");
        System.out.println(" idx |  snap | preSnap | sigma | distPrev | inGap |  edgeId  | filt | baseline | emHigh | expandHi | offGrid");
        System.out.println("-----|-------|---------|-------|----------|-------|----------|------|----------|--------|----------|--------");
        for (int i = from; i <= to; i++) {
            Tracepoint tp = tps.get(i);
            double base = v2LocalBaseline(snap, n, i);
            double s = snap[i];
            boolean emHigh, expandHigh, offGrid;
            if (Double.isNaN(s)) {
                emHigh = true; expandHigh = true; offGrid = true;
            } else {
                emHigh = s > snapThreshold
                        || (s > RegionSegmenter.V2_EMISSION_TRIGGER_FLOOR_M
                            && s > RegionSegmenter.V2_EMISSION_TRIGGER_MULT * base);
                expandHigh = s > RegionSegmenter.V2_EXPAND_FLOOR_M
                        && s > RegionSegmenter.V2_EXPAND_MULT * base;
                offGrid = s > snapThreshold;
            }
            String sn = Double.isNaN(s) ? "  NaN" : String.format("%5.1f", s);
            String ps = (prePassSnap != null && i < prePassSnap.length && !Double.isNaN(prePassSnap[i]))
                    ? String.format("%7.1f", prePassSnap[i]) : "    N/A";
            String sg = (sigmaPerObs != null && i < sigmaPerObs.length)
                    ? String.format("%5.1f", sigmaPerObs[i]) : "  N/A";
            String dp = tp.getDistanceFromPrevious() != null
                    ? String.format("%8.1f", tp.getDistanceFromPrevious()) : "     N/A";
            // Straight-line input gap to the previous observation's ORIGINAL point — reveals
            // near-coincident input points (and whether a point is original or interpolated).
            String inGap = "  N/A";
            if (i > 0 && tp.getOriginalPoint() != null && tps.get(i - 1).getOriginalPoint() != null) {
                inGap = String.format("%5.1f", DistanceCalcEarth.DIST_EARTH.calcDist(
                        tp.getOriginalPoint().lat, tp.getOriginalPoint().lon,
                        tps.get(i - 1).getOriginalPoint().lat, tps.get(i - 1).getOriginalPoint().lon));
            }
            System.out.printf(" %4d | %s | %s | %s | %s | %s | %8s | %4s | %8.1f | %6s | %8s | %s%n",
                    i, sn, ps, sg, dp, inGap,
                    tp.getEdgeId() != null ? tp.getEdgeId().toString() : "null",
                    tp.isFiltered(), base, emHigh, expandHigh, offGrid);
        }
    }

    /** Dump the matcher's per-candidate internal costs (emission, transition of best incoming
     *  connection, accumulated) for each observation in a window — the authoritative numbers for
     *  "is transition overpowering emission?". Needs cfg.debugCandidateCosts=true. */
    private static void dumpCandidateCosts(Map<String, Object> stats, List<Observation> obs,
                                           int from, int to) {
        Object cc = stats.get("candidateCosts");
        if (!(cc instanceof List)) {
            System.out.println("(no candidateCosts — debugCandidateCosts not set)");
            return;
        }
        Map<String, Integer> obsKey = new HashMap<>();
        for (int i = Math.max(0, from); i <= Math.min(obs.size() - 1, to); i++) {
            GHPoint p = obs.get(i).getPoint();
            obsKey.put(p.lat + "_" + p.lon, i);
        }
        Map<Integer, List<TrailmapMapMatching.CandidateCost>> byObs = new java.util.TreeMap<>();
        for (Object o : (List<?>) cc) {
            TrailmapMapMatching.CandidateCost c = (TrailmapMapMatching.CandidateCost) o;
            Integer idx = obsKey.get(c.obsLat + "_" + c.obsLon);
            if (idx == null) continue;
            byObs.computeIfAbsent(idx, k -> new ArrayList<>()).add(c);
        }
        System.out.printf("=== candidate costs obs[%d..%d]  (emission + transition-of-best-incoming = accum) ===%n",
                from, to);
        System.out.println(" obs |  edgeId  | snapM | emisCost | transCost | tripLenM | accumCost | lowest-accum?");
        for (var e : byObs.entrySet()) {
            List<TrailmapMapMatching.CandidateCost> cands = e.getValue();
            cands.sort(java.util.Comparator.comparingDouble(x -> x.accumulatedCost));
            for (int k = 0; k < cands.size(); k++) {
                TrailmapMapMatching.CandidateCost c = cands.get(k);
                System.out.printf(" %4d | %8d | %5.1f | %8.2f | %9s | %8s | %9.2f | %s%n",
                        e.getKey(), c.edgeId, c.snapDistanceM, c.emissionCost,
                        c.transitionCost == null ? "    -" : String.format("%.2f", c.transitionCost),
                        c.transitionTripLengthM == null ? "    -" : String.format("%.1f", c.transitionTripLengthM),
                        c.accumulatedCost, k == 0 ? "<= lowest" : "");
            }
        }
    }

    private static double v2LocalBaseline(double[] snap, int n, int i) {
        int lo = Math.max(0, i - RegionSegmenter.V2_EMISSION_WINDOW);
        int hi = Math.min(n - 1, i + RegionSegmenter.V2_EMISSION_WINDOW);
        List<Double> win = new ArrayList<>();
        for (int j = lo; j <= hi; j++) if (!Double.isNaN(snap[j])) win.add(snap[j]);
        double b;
        if (win.isEmpty()) {
            b = RegionSegmenter.V2_EMISSION_BASELINE_MIN_M;
        } else {
            java.util.Collections.sort(win);
            double p = RegionSegmenter.V2_EMISSION_BASELINE_PCTL;
            double rank = p * (win.size() - 1);
            int l = (int) Math.floor(rank), h = (int) Math.ceil(rank);
            b = win.get(l) + (rank - l) * (win.get(h) - win.get(l));
        }
        return Math.max(RegionSegmenter.V2_EMISSION_BASELINE_MIN_M,
                Math.min(RegionSegmenter.V2_EMISSION_BASELINE_MAX_M, b));
    }

    /**
     * Deep diagnostic dump for investigating waypoint-optimization issues.
     *
     * <p>Replicates the segmenter + optimizer logic locally with full per-step printing —
     * does NOT call the production converter, so we can see edge-by-edge what the
     * algorithm "sees" without touching production code.
     *
     * <p>What it prints:
     * <ol>
     *   <li>Per-observation: original GPS, snap position, snap distance, edge id, matched/filtered flags</li>
     *   <li>The full EdgeMatch list (edge ids + distances)</li>
     *   <li>The obs → EdgeMatch index mapping (with notes when forward/backward search was needed)</li>
     *   <li>Snap-based good/bad classification, with explicit notes when de-isolation flipped a value</li>
     *   <li>For each Matched region: full edge slice + per-obs slice-index mapping</li>
     *   <li>For each Matched region's optimizer: for every probe, the expected edge slice vs the
     *       actual route's edge sequence, dedup'd, with a clear pass/fail verdict and reason</li>
     * </ol>
     *
     * <p>Run: {@code -Dtest=TrackConvertDiagnosticTest#diagnoseProbes
     *   -Dconvert.gpx=/abs/path.gpx -Dconvert.profile=... }
     */
    @Test
    void diagnoseProbes() throws Exception {
        String gpxPath = System.getProperty("convert.gpx");
        Assumptions.assumeTrue(gpxPath != null,
                "Pass -Dconvert.gpx=/abs/path/to/file.gpx to run this test");
        String profile = System.getProperty("convert.profile", "gravel");
        double gpsAccuracy = Double.parseDouble(System.getProperty("convert.gpsAccuracy", "20"));
        double snapThreshold = Double.parseDouble(System.getProperty("convert.snapThreshold", "35"));

        List<Observation> observations = parseGpx(new File(gpxPath));
        System.out.println("=== INPUT ===");
        System.out.println("gpx=" + gpxPath);
        System.out.println("profile=" + profile + " gpsAccuracy=" + gpsAccuracy + " snapThreshold=" + snapThreshold);
        System.out.println("observations=" + observations.size());

        PMap hints = new PMap();
        hints.putObject("profile", profile);
        MapMatching matching = MapMatching.fromGraphHopper(hopper, hints);
        matching.setMeasurementErrorSigma(gpsAccuracy);
        MatchResult mr = matching.match(observations);
        System.out.println();
        System.out.println("=== MAPMATCHING RESULT ===");
        System.out.println("edgeMatches=" + mr.getEdgeMatches().size()
                + " tracepoints=" + (mr.getTracepoints() != null ? mr.getTracepoints().size() : 0)
                + " matchLengthM=" + Math.round(mr.getMatchLength()));

        // --- Per-observation tracepoint dump ---
        List<Tracepoint> tps = mr.getTracepoints();
        System.out.println();
        System.out.println("=== TRACEPOINTS (one row per input observation) ===");
        System.out.println("idx |  origin (lat,lon)       |  snap (lat,lon)         | snap_dist | distFromPrev |  edge_id | matched | filtered");
        System.out.println("----|-------------------------|-------------------------|-----------|--------------|----------|---------|---------");
        for (int i = 0; i < tps.size(); i++) {
            Tracepoint tp = tps.get(i);
            String snap = tp.getSnappedPoint() != null
                    ? String.format("(%.6f, %.6f)", tp.getSnappedPoint().lat, tp.getSnappedPoint().lon)
                    : "       N/A          ";
            String d = tp.getDistance() != null ? String.format("%6.1fm", tp.getDistance()) : "    N/A";
            String dfp = tp.getDistanceFromPrevious() != null
                    ? String.format("%9.1fm", tp.getDistanceFromPrevious()) : "      N/A";
            System.out.printf("%3d | (%.6f, %.6f) | %s |  %s  | %s   | %8s | %7s | %8s%n",
                    i,
                    tp.getOriginalPoint().lat, tp.getOriginalPoint().lon,
                    snap, d, dfp,
                    tp.getEdgeId() != null ? tp.getEdgeId().toString() : "    null",
                    tp.isMatched(), tp.isFiltered());
        }

        // --- EdgeMatch list ---
        System.out.println();
        System.out.println("=== EDGE MATCHES (the matched path's edge sequence) ===");
        for (int e = 0; e < mr.getEdgeMatches().size(); e++) {
            EdgeMatch em = mr.getEdgeMatches().get(e);
            PointList g = em.getEdgeState().fetchWayGeometry(FetchMode.ALL);
            System.out.printf("em[%2d] edgeId=%-8d dist=%6.1fm geomPts=%d states=%d%n",
                    e, em.getEdgeState().getEdge(),
                    em.getEdgeState().getDistance(),
                    g.size(), em.getStates().size());
        }

        // --- Replicate obsToEdgeMatch (annotate forward/backward) ---
        int n = tps.size();
        int[] obsToEm = new int[n];
        String[] obsToEmNote = new String[n];
        for (int i = 0; i < n; i++) obsToEm[i] = -1;
        int searchFrom = 0;
        for (int i = 0; i < n; i++) {
            Tracepoint tp = tps.get(i);
            if (!tp.isMatched() || tp.getEdgeId() == null) {
                obsToEmNote[i] = "no edge id";
                continue;
            }
            int target = tp.getEdgeId();
            int found = -1;
            for (int j = searchFrom; j < mr.getEdgeMatches().size(); j++) {
                if (mr.getEdgeMatches().get(j).getEdgeState().getEdge() == target) {
                    found = j; break;
                }
            }
            if (found < 0) {
                for (int j = searchFrom - 1; j >= 0; j--) {
                    if (mr.getEdgeMatches().get(j).getEdgeState().getEdge() == target) {
                        found = j;
                        obsToEmNote[i] = "BACKWARD scan";
                        break;
                    }
                }
            } else {
                obsToEmNote[i] = "forward";
            }
            if (found >= 0) {
                obsToEm[i] = found;
                searchFrom = found;
            } else {
                obsToEmNote[i] = "NOT FOUND in EdgeMatches";
            }
        }

        // --- Snap-based classification + de-isolation ---
        boolean[] good0 = new boolean[n];
        for (int i = 0; i < n; i++) {
            Tracepoint tp = tps.get(i);
            good0[i] = tp.isMatched() && tp.getDistance() != null && tp.getDistance() < snapThreshold;
        }
        boolean[] good = good0.clone();
        boolean[] flipped = new boolean[n];
        if (n >= 3) {
            boolean[] orig = good.clone();
            for (int i = 1; i < n - 1; i++) {
                if (orig[i - 1] == orig[i + 1] && orig[i] != orig[i - 1]) {
                    good[i] = orig[i - 1];
                    flipped[i] = true;
                }
            }
            if (n >= 2 && good[0] != good[1]) { good[0] = good[1]; flipped[0] = true; }
            if (n >= 2 && good[n - 1] != good[n - 2]) { good[n - 1] = good[n - 2]; flipped[n - 1] = true; }
        }
        System.out.println();
        System.out.println("=== OBS → EDGEMATCH MAPPING + CLASSIFICATION ===");
        System.out.println("idx | snap_dist | edgeId   | obsToEm | scan note          | good0 (pre-deiso) | good (final) | flipped?");
        System.out.println("----|-----------|----------|---------|--------------------|--------------------|--------------|----------");
        for (int i = 0; i < n; i++) {
            Tracepoint tp = tps.get(i);
            String d = tp.getDistance() != null ? String.format("%6.1fm", tp.getDistance()) : "    N/A";
            System.out.printf("%3d | %s | %-8s |  em[%3d] | %-18s |   %-15s |    %-9s |   %s%n",
                    i, d,
                    tp.getEdgeId() != null ? tp.getEdgeId().toString() : "null",
                    obsToEm[i], obsToEmNote[i],
                    good0[i] ? "good" : "BAD",
                    good[i] ? "good" : "BAD",
                    flipped[i] ? "*FLIPPED*" : "");
        }

        // --- Region building (mimic) ---
        System.out.println();
        System.out.println("=== REGIONS (snap-based only — detour-split not replayed here) ===");
        int i = 0;
        List<int[]> regs = new ArrayList<>();  // [start, end, isMatched? 1:0]
        while (i < n) {
            int start = i;
            boolean run = good[i];
            int j = i;
            while (j + 1 < n && good[j + 1] == run) j++;
            regs.add(new int[]{start, j, run ? 1 : 0});
            i = j + 1;
        }
        for (int[] r : regs) {
            System.out.printf("  %s [%d..%d]  (%d obs)%n",
                    r[2] == 1 ? "Matched  " : "Unmatched",
                    r[0], r[1], r[1] - r[0] + 1);
        }

        // --- Per matched region: full edge slice + per-probe instrumentation ---
        for (int[] r : regs) {
            if (r[2] != 1) continue;
            int startObs = r[0], endObs = r[1];
            // Build edge slice
            int firstEm = -1, lastEm = -1;
            for (int k = startObs; k <= endObs; k++) {
                if (obsToEm[k] >= 0) {
                    if (firstEm < 0) firstEm = obsToEm[k];
                    lastEm = obsToEm[k];
                }
            }
            if (firstEm < 0) continue;

            // Collect well-mapped obs in region
            List<int[]> wellMapped = new ArrayList<>(); // [obsIdx, edgeIdxInSlice]
            for (int k = startObs; k <= endObs; k++) {
                if (obsToEm[k] < 0) continue;
                Tracepoint tp = tps.get(k);
                if (tp.getSnappedPoint() == null) continue;
                wellMapped.add(new int[]{k, obsToEm[k] - firstEm});
            }
            if (wellMapped.size() < 2) {
                System.out.printf("%n=== REGION Matched [%d..%d]: only %d well-mapped obs, skipping probe diagnostic%n",
                        startObs, endObs, wellMapped.size());
                continue;
            }

            // Print the slice
            System.out.printf("%n=== REGION Matched [%d..%d]  edges em[%d..%d]  (%d edges in slice) ===%n",
                    startObs, endObs, firstEm, lastEm, lastEm - firstEm + 1);
            System.out.print("Edge slice IDs: [");
            for (int e = firstEm; e <= lastEm; e++) {
                if (e > firstEm) System.out.print(", ");
                System.out.print(mr.getEdgeMatches().get(e).getEdgeState().getEdge());
            }
            System.out.println("]");

            System.out.println("Candidates (obs index, edge-idx-in-slice, snap lat,lon):");
            for (int k = 0; k < wellMapped.size(); k++) {
                int obsIdx = wellMapped.get(k)[0];
                int edgeIdx = wellMapped.get(k)[1];
                GHPoint s = tps.get(obsIdx).getSnappedPoint();
                System.out.printf("  c[%2d] obs[%d] edgeIdxInSlice=%d snap=(%.6f, %.6f)%n",
                        k, obsIdx, edgeIdx, s.lat, s.lon);
            }

            // For every consecutive pair AND every long-range probe combination tried by exponential
            // extension, run the probe and print full diagnostics. We don't run the actual optimizer
            // here — just enumerate the probes its loop would issue.
            System.out.println("Probes (replicating exponential-extension + binary-refinement):");
            int cursor = 0;
            int lastCand = wellMapped.size() - 1;
            while (cursor < lastCand) {
                int step = 1;
                int lastOk = -1;
                int lastTried = cursor;
                while (cursor + step <= lastCand) {
                    int probeIdx = Math.min(cursor + step, lastCand);
                    lastTried = probeIdx;
                    boolean ok = probeAndPrint(profile, wellMapped, mr.getEdgeMatches(), firstEm,
                            tps, cursor, probeIdx);
                    if (ok) {
                        lastOk = probeIdx;
                        if (probeIdx == lastCand) break;
                        step *= 2;
                    } else {
                        break;
                    }
                }
                if (lastOk < 0) {
                    // forced single step
                    int next = cursor + 1;
                    probeAndPrint(profile, wellMapped, mr.getEdgeMatches(), firstEm,
                            tps, cursor, next);
                    System.out.printf("  → forced step: cursor %d → %d%n", cursor, next);
                    cursor = next;
                    continue;
                }
                int lo = lastOk + 1;
                int hi = lastTried;
                int best = lastOk;
                while (lo <= hi) {
                    int mid = (lo + hi) / 2;
                    boolean ok = probeAndPrint(profile, wellMapped, mr.getEdgeMatches(), firstEm,
                            tps, cursor, mid);
                    if (ok) { best = mid; lo = mid + 1; }
                    else { hi = mid - 1; }
                }
                System.out.printf("  → cursor %d → %d (best successful probe)%n", cursor, best);
                cursor = best;
            }
        }
    }

    /**
     * Run a probe and print its full input + output. Returns the pass/fail verdict using
     * the same comparison rule the production optimizer uses (interior edges match,
     * up to 1 leading + 2 trailing virtual-edge tolerance).
     */
    private boolean probeAndPrint(String profile,
                                  List<int[]> wellMapped,
                                  List<EdgeMatch> em,
                                  int firstEm,
                                  List<Tracepoint> tps,
                                  int startCand, int endCand) {
        int startObs = wellMapped.get(startCand)[0];
        int endObs = wellMapped.get(endCand)[0];
        int eFrom = Math.min(wellMapped.get(startCand)[1], wellMapped.get(endCand)[1]);
        int eTo = Math.max(wellMapped.get(startCand)[1], wellMapped.get(endCand)[1]);
        GHPoint pStart = tps.get(startObs).getSnappedPoint();
        GHPoint pEnd = tps.get(endObs).getSnappedPoint();

        GHRequest req = new GHRequest(pStart, pEnd);
        req.setProfile(profile);
        req.setPathDetails(List.of("edge_id"));
        req.putHint("instructions", false);
        req.putHint("calc_points", true);

        StringBuilder header = new StringBuilder();
        header.append(String.format("  probe c[%d]→c[%d] (obs[%d]→obs[%d], expected slice[%d..%d]):",
                startCand, endCand, startObs, endObs, eFrom, eTo));

        GHResponse rsp;
        try { rsp = hopper.route(req); }
        catch (Exception ex) {
            System.out.println(header + " ROUTING THREW: " + ex.getMessage() + "  → FAIL");
            return false;
        }
        if (rsp.hasErrors()) {
            System.out.println(header + " ROUTE ERROR: " + rsp.getErrors() + "  → FAIL");
            return false;
        }
        ResponsePath path = rsp.getBest();
        List<PathDetail> details = path.getPathDetails().get("edge_id");
        if (details == null || details.isEmpty()) {
            System.out.println(header + " NO edge_id DETAILS  → FAIL");
            return false;
        }

        // Dedup consecutive identical edge IDs in route
        List<Integer> routeEdges = new ArrayList<>(details.size());
        int prev = Integer.MIN_VALUE;
        for (PathDetail d : details) {
            int eid = ((Number) d.getValue()).intValue();
            if (eid != prev) { routeEdges.add(eid); prev = eid; }
        }

        // Expected
        List<Integer> expected = new ArrayList<>();
        for (int e = eFrom; e <= eTo; e++) expected.add(em.get(firstEm + e).getEdgeState().getEdge());

        // Verdict using same rule as RoutedRegionOptimizer.probe
        boolean ok;
        String reason;
        if (eFrom == eTo) {
            // same edge — accept if target appears anywhere in route
            int target = expected.get(0);
            ok = routeEdges.contains(target);
            reason = ok ? "same-edge target found" : "same-edge target NOT in route";
        } else {
            // find expected[0] in first 2 of route
            int rIdx = -1;
            for (int k = 0; k < Math.min(2, routeEdges.size()); k++) {
                if (routeEdges.get(k).equals(expected.get(0))) { rIdx = k; break; }
            }
            if (rIdx < 0) {
                ok = false;
                reason = "expected[0]=" + expected.get(0) + " not in route[0..1]";
            } else {
                int ei = 0;
                boolean diverged = false;
                while (ei < expected.size() && rIdx < routeEdges.size()) {
                    if (!routeEdges.get(rIdx).equals(expected.get(ei))) {
                        diverged = true;
                        break;
                    }
                    rIdx++; ei++;
                }
                if (diverged) {
                    ok = false;
                    reason = "mismatch at expected[" + ei + "]=" + expected.get(ei)
                            + " vs route[" + rIdx + "]=" + routeEdges.get(rIdx);
                } else if (ei < expected.size()) {
                    ok = false;
                    reason = "ran out of route at expected[" + ei + "]";
                } else if (routeEdges.size() - rIdx > 2) {
                    ok = false;
                    reason = "too many trailing extras: " + (routeEdges.size() - rIdx);
                } else {
                    ok = true;
                    reason = "exact sequence match (trailing extras: " + (routeEdges.size() - rIdx) + ")";
                }
            }
        }

        // ---- Geometric instrumentation (independent of strict verdict) ----
        // Build the matched polyline by walking slice edges' geometries.
        PointList matchedPoly = new PointList(64, false);
        for (int e = eFrom; e <= eTo; e++) {
            PointList g = em.get(firstEm + e).getEdgeState().fetchWayGeometry(
                    e == eFrom ? FetchMode.ALL : FetchMode.PILLAR_AND_ADJ);
            for (int j = 0; j < g.size(); j++) {
                matchedPoly.add(g.getLat(j), g.getLon(j));
            }
        }
        // Sum of slice edge full lengths (what production code uses as "expectedLen")
        double sliceFullLen = 0;
        for (int e = eFrom; e <= eTo; e++) {
            sliceFullLen += em.get(firstEm + e).getEdgeState().getDistance();
        }
        double routeLen = path.getDistance();
        double ratioDiffPct = sliceFullLen > 0
                ? Math.abs(routeLen - sliceFullLen) / Math.max(routeLen, sliceFullLen) * 100.0
                : 0;

        PointList routePoly = path.getPoints();
        // Max deviation: every /route point → matched polyline (Hausdorff one-way, the
        // metric the production geometric fallback uses).
        double maxRouteToMatched = 0;
        if (matchedPoly.size() >= 2 && routePoly.size() >= 1) {
            for (int j = 0; j < routePoly.size(); j++) {
                double d = diagPointToPolylineDistance(
                        routePoly.getLat(j), routePoly.getLon(j), matchedPoly);
                if (d > maxRouteToMatched) maxRouteToMatched = d;
            }
        }
        // Max deviation: every matched-polyline point → route polyline (the reverse, to
        // catch the case where matched goes through a section /route skips entirely).
        double maxMatchedToRoute = 0;
        if (routePoly.size() >= 2 && matchedPoly.size() >= 1) {
            for (int j = 0; j < matchedPoly.size(); j++) {
                double d = diagPointToPolylineDistance(
                        matchedPoly.getLat(j), matchedPoly.getLon(j), routePoly);
                if (d > maxMatchedToRoute) maxMatchedToRoute = d;
            }
        }

        System.out.println(header);
        System.out.println("    expected (" + expected.size() + "): " + expected);
        System.out.println("    actual   (" + routeEdges.size() + "): " + routeEdges);
        System.out.println("    distance=" + Math.round(path.getDistance()) + "m → " + (ok ? "PASS" : "FAIL")
                + " (" + reason + ")");
        System.out.printf("    [GEO] sliceFullLen=%.1fm routeLen=%.1fm lenRatioDiff=%.1f%% "
                        + "| maxDev route→matched=%.2fm matched→route=%.2fm%n",
                sliceFullLen, routeLen, ratioDiffPct, maxRouteToMatched, maxMatchedToRoute);
        return ok;
    }

    /** Test-side helper: min distance from a single point to a polyline. */
    private static double diagPointToPolylineDistance(double pLat, double pLon, PointList line) {
        double min = Double.POSITIVE_INFINITY;
        if (line.size() == 1) {
            return DistanceCalcEarth.DIST_EARTH.calcDist(pLat, pLon, line.getLat(0), line.getLon(0));
        }
        for (int i = 0; i + 1 < line.size(); i++) {
            double d = diagPointToSegmentDistance(pLat, pLon,
                    line.getLat(i), line.getLon(i),
                    line.getLat(i + 1), line.getLon(i + 1));
            if (d < min) min = d;
        }
        return min;
    }

    /** Test-side helper: perpendicular point-to-segment distance, clamped to endpoints. */
    private static double diagPointToSegmentDistance(double pLat, double pLon,
                                                     double aLat, double aLon,
                                                     double bLat, double bLon) {
        double meanLatRad = Math.toRadians((aLat + bLat) * 0.5);
        double mPerDegLat = 111_320.0;
        double mPerDegLon = 111_320.0 * Math.cos(meanLatRad);
        double ax = aLon * mPerDegLon, ay = aLat * mPerDegLat;
        double bx = bLon * mPerDegLon, by = bLat * mPerDegLat;
        double px = pLon * mPerDegLon, py = pLat * mPerDegLat;
        double dx = bx - ax, dy = by - ay;
        double segLenSq = dx * dx + dy * dy;
        if (segLenSq == 0) {
            return DistanceCalcEarth.DIST_EARTH.calcDist(pLat, pLon, aLat, aLon);
        }
        double t = ((px - ax) * dx + (py - ay) * dy) / segLenSq;
        if (t < 0) t = 0;
        else if (t > 1) t = 1;
        double cx = ax + t * dx;
        double cy = ay + t * dy;
        return Math.sqrt((px - cx) * (px - cx) + (py - cy) * (py - cy));
    }

