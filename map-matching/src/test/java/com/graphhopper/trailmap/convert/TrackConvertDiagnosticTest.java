    // ----------------------------------------------------------------------
    // TRANSITION-COST DIAGNOSTIC (M2a lambda sizing)
    //
    // Uses the FORK's real internal HMM costs (MatcherConfig.debugCandidateCosts),
    // not a geometric proxy. For the target observation, per candidate way:
    //   emissionCost     — snap-distance penalty (what an M2a desirability term adds to)
    //   transitionCost   — penalty of the best incoming forward-trip
    //   tripLen          — that connecting trip's length (m)
    //   accumulatedCost  — best whole-trip-so-far cost (the number the matcher compares)
    //   wgt/m            — routing weight per metre (the proposed M2a desirability signal)
    // and the lambda needed for the most-desirable (lowest wgt/m) way to win:
    //   lambda > (acc_good - acc_cand) / ln(wpm_cand / wpm_min)
    //
    // NOTE: accumulated-cost-at-this-observation is a LOCAL proxy for the global
    // flip — it ignores how the choice changes costs further down the track. Good
    // enough to size lambda; not an exact whole-sequence prediction.
    //
    // Usage:
    //   -Dtest=TrackConvertDiagnosticTest#diagnoseTransitionCost
    //   -Dconvert.gpx=/abs/path.gpx -Dconvert.profile=gravel
    //   -Dconvert.gpsAccuracy=20 -Dconvert.targetObs=6
    // ----------------------------------------------------------------------
    @Test
    void diagnoseTransitionCost() throws Exception {
        String gpxPath = System.getProperty("convert.gpx");
        Assumptions.assumeTrue(gpxPath != null, "Pass -Dconvert.gpx=...");
        String profileName = System.getProperty("convert.profile", "gravel");
        double sigma = Double.parseDouble(System.getProperty("convert.gpsAccuracy", "20"));
        int target = Integer.parseInt(System.getProperty("convert.targetObs", "6"));

        List<Observation> observations = parseGpx(new File(gpxPath));
        PMap hints = new PMap();
        hints.putObject("profile", profileName);
        MatcherConfig cfg = new MatcherConfig();
        cfg.measurementErrorSigma = sigma;
        cfg.debugCandidateCosts = true;
        // Optional M2a sweep: -Dconvert.lambda=1.0 -Dconvert.tau=1.5 turns on the
        // profile-aware emission penalty so we can watch the chosen edge flip.
        String lamProp = System.getProperty("convert.lambda");
        if (lamProp != null) {
            cfg.emissionDesirabilityLambda = Double.parseDouble(lamProp);
            cfg.emissionDesirabilityDeadband = Double.parseDouble(System.getProperty("convert.tau", "1.5"));
        }
        TrailmapMapMatching matching = TrailmapMapMatching.fromGraphHopper(hopper, hints, cfg);
        MatchResult mr = matching.match(observations);
        List<Tracepoint> tps = mr.getTracepoints();
        @SuppressWarnings("unchecked")
        List<TrailmapMapMatching.CandidateCost> allCosts =
                (List<TrailmapMapMatching.CandidateCost>) matching.getStatistics().get("candidateCosts");

        EncodingManager em = hopper.getEncodingManager();
        EnumEncodedValue<?> roadClassEv = em.getEnumEncodedValue("road_class", enumClass(em, "road_class"));
        DecimalEncodedValue gravelPrioEv = em.hasEncodedValue("gravel_base_priority")
                ? em.getDecimalEncodedValue("gravel_base_priority") : null;
        DecimalEncodedValue gravelScaleNumEv = em.hasEncodedValue("gravel_scale_num")
                ? em.getDecimalEncodedValue("gravel_scale_num") : null;
        Weighting weighting = hopper.createWeighting(hopper.getProfile(profileName), new PMap());

        GHPoint tgt = observations.get(target).getPoint();
        // Best (lowest accumulated cost) record per edge id at the target observation.
        Map<Integer, TrailmapMapMatching.CandidateCost> byEdge = new LinkedHashMap<>();
        if (allCosts != null) {
            for (TrailmapMapMatching.CandidateCost c : allCosts) {
                if (Math.abs(c.obsLat - tgt.lat) < 1e-9 && Math.abs(c.obsLon - tgt.lon) < 1e-9) {
                    TrailmapMapMatching.CandidateCost prev = byEdge.get(c.edgeId);
                    if (prev == null || c.accumulatedCost < prev.accumulatedCost) byEdge.put(c.edgeId, c);
                }
            }
        }

        // Edge attributes (edgeId -> edge) via the candidate snaps.
        List<Snap> snaps = matching.findCandidateSnaps(tgt.lat, tgt.lon);
        Map<Integer, EdgeIteratorState> edgeById = new HashMap<>();
        for (Snap s : snaps) edgeById.put(s.getClosestEdge().getEdge(), s.getClosestEdge());

        double wpmMin = Double.MAX_VALUE;
        Map<Integer, Double> wpmByEdge = new HashMap<>();
        for (Integer eid : byEdge.keySet()) {
            EdgeIteratorState edge = edgeById.get(eid);
            double w = (edge != null && edge.getDistance() > 0)
                    ? weighting.calcEdgeWeight(edge, false) / edge.getDistance() : Double.NaN;
            wpmByEdge.put(eid, w);
            if (!Double.isNaN(w) && w < wpmMin) wpmMin = w;
        }
        double bestDesirableAcc = Double.MAX_VALUE;
        for (Integer eid : byEdge.keySet()) {
            Double w = wpmByEdge.get(eid);
            if (w != null && !Double.isNaN(w) && Math.abs(w - wpmMin) < 1e-9)
                bestDesirableAcc = Math.min(bestDesirableAcc, byEdge.get(eid).accumulatedCost);
        }

        System.out.printf("%n=== TRANSITION COST OBS[%d] sigma=%.1f beta=%.1f  M2a=%s  chosenEdge=%s ===%n",
                target, sigma, cfg.transitionProbabilityBeta,
                cfg.isEmissionDesirabilityOn()
                        ? ("lambda=" + cfg.emissionDesirabilityLambda + " tau=" + cfg.emissionDesirabilityDeadband)
                        : "off",
                tps.get(target).getEdgeId());
        System.out.println("  edge_id  | class      | snap | prio | gScl | wgt/m  | emCost | transCost | tripLen | accumCost | lambda_to_win");
        System.out.println("  ---------|------------|------|------|------|--------|--------|-----------|---------|-----------|--------------");
        for (Map.Entry<Integer, TrailmapMapMatching.CandidateCost> e : byEdge.entrySet()) {
            int eid = e.getKey();
            TrailmapMapMatching.CandidateCost c = e.getValue();
            EdgeIteratorState edge = edgeById.get(eid);
            String rc = edge != null ? edge.get(roadClassEv).toString() : "?";
            String gp = (edge != null && gravelPrioEv != null) ? String.format("%.2f", edge.get(gravelPrioEv)) : "?";
            String gs = (edge != null && gravelScaleNumEv != null) ? String.format("%.2f", edge.get(gravelScaleNumEv)) : "?";
            double w = wpmByEdge.getOrDefault(eid, Double.NaN);
            String lam;
            double pen = (wpmMin > 0 && !Double.isNaN(w)) ? Math.log(w / wpmMin) : 0;
            if (pen < 1e-9) {
                lam = "(most desirable)";
            } else {
                double needed = (bestDesirableAcc - c.accumulatedCost) / pen;
                lam = needed <= 0 ? "0 (already wins)" : String.format("%.2f", needed);
            }
            boolean chosen = tps.get(target).getEdgeId() != null && tps.get(target).getEdgeId() == eid;
            System.out.printf("  %-8d | %-10s | %4.1f | %-4s | %-4s | %6.3f | %6.3f | %9s | %7s | %9.3f | %s%s%n",
                    eid, rc, c.snapDistanceM, gp, gs, w, c.emissionCost,
                    c.transitionCost == null ? "-" : String.format("%.3f", c.transitionCost),
                    c.transitionTripLengthM == null ? "-" : String.format("%.1f", c.transitionTripLengthM),
                    c.accumulatedCost, lam, chosen ? "  <== CHOSEN" : "");
        }
    }

