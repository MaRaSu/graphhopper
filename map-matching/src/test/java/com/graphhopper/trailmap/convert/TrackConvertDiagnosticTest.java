    /**
     * V1 (adaptive-σ premise check, DIAGNOSTIC ONLY — no production change). Question: does the
     * apparent per-observation σ (nearest-snap distance) vary meaningfully ALONG each track, so
     * that a single global σ is a poor fit? Runs a snap-only pre-pass (the existing public
     * {@code findCandidateSnaps}, nearest only, NO Viterbi) on the client's densified track and
     * characterises the local-σ profile vs the single global σ the current system uses.
     */
    @Test
    void analyzeSigmaProfileV1() throws Exception {
        String[][] cases = {
                {"sbc_keha_g.gpx", "gravel"},
                {"sorel.gpx", "trailmap_foot"},
                {"trail_run_snap.gpx", "trailmap_foot"},
                {"l_93km.gpx", "gravel"},
        };
        double densifyGap = 40.0;
        int[] windows = {5, 15, 30};
        for (String[] c : cases) {
            File f = new File("../../data/gpx-for-testing/" + c[0]);
            if (!f.exists()) { System.out.println("MISSING " + c[0]); continue; }
            List<Observation> obs = parseGpx(f);
            int raw = obs.size();
            obs = com.graphhopper.trailmap.matching.ObservationDensifier.densify(obs, densifyGap);
            int n = obs.size();
            PMap hints = new PMap();
            hints.putObject("profile", c[1]);
            TrailmapMapMatching fork = TrailmapMapMatching.fromGraphHopper(hopper, hints, new MatcherConfig());
            double[] d = new double[n];
            int found = 0;
            for (int i = 0; i < n; i++) {
                GHPoint p = obs.get(i).getPoint();
                List<Snap> snaps = fork.findCandidateSnaps(p.lat, p.lon);
                if (snaps.isEmpty()) { d[i] = Double.NaN; continue; }
                d[i] = snaps.get(0).getQueryDistance();
                found++;
            }
            double[] sorted = Arrays.stream(d).filter(x -> !Double.isNaN(x)).sorted().toArray();
            double[] onGrid = Arrays.stream(d).filter(x -> !Double.isNaN(x) && x <= 40).sorted().toArray();
            double globalSigma = Math.max(4, Math.min(10, pctlArr(onGrid, 0.9)));
            long offG25 = Arrays.stream(d).filter(x -> !Double.isNaN(x) && x > 25).count();
            long offG40 = Arrays.stream(d).filter(x -> !Double.isNaN(x) && x > 40).count();
            System.out.printf("%n=== %s (%s) raw=%d densified=%d snapped=%d ===%n", c[0], c[1], raw, n, found);
            System.out.printf("  nearest-snap d: p10=%.1f p50=%.1f p90=%.1f p99=%.1f max=%.1f%n",
                    pctlArr(sorted, 0.10), pctlArr(sorted, 0.50), pctlArr(sorted, 0.90),
                    pctlArr(sorted, 0.99), sorted.length > 0 ? sorted[sorted.length - 1] : Double.NaN);
            System.out.printf("  current global σ proxy (0.9pctl on-grid, clamp[4,10]) = %.1f%n", globalSigma);
            System.out.printf("  off-grid: %.1f%% > 25m, %.1f%% > 40m%n", 100.0 * offG25 / n, 100.0 * offG40 / n);
            for (int W : windows) {
                double[] wmed = windowedMedian(d, n, W);
                double[] ws = Arrays.stream(wmed).filter(x -> !Double.isNaN(x)).sorted().toArray();
                double w10 = pctlArr(ws, 0.10), w50 = pctlArr(ws, 0.50), w90 = pctlArr(ws, 0.90);
                double jit = 0; int jn = 0;
                for (int i = 1; i < n; i++) {
                    if (!Double.isNaN(wmed[i]) && !Double.isNaN(wmed[i - 1])) { jit += Math.abs(wmed[i] - wmed[i - 1]); jn++; }
                }
                System.out.printf("  W=%2d windowed-median σ: p10=%.1f p50=%.1f p90=%.1f  swing(p90/p10)=%.2f  stepJitter=%.2fm/obs%n",
                        W, w10, w50, w90, w10 > 0 ? w90 / w10 : Double.NaN, jn > 0 ? jit / jn : Double.NaN);
            }
            double[] wmed = windowedMedian(d, n, 15);
            StringBuilder sb = new StringBuilder("  decile local-median σ (W=15, start→end): ");
            for (int dc = 0; dc < 10; dc++) {
                int a = dc * n / 10, b = (dc + 1) * n / 10;
                double[] seg = Arrays.stream(wmed, a, Math.max(a + 1, b)).filter(x -> !Double.isNaN(x)).sorted().toArray();
                sb.append(String.format("%.1f ", seg.length > 0 ? pctlArr(seg, 0.5) : Double.NaN));
            }
            System.out.println(sb);
        }
        assertTrue(true);
    }

    private static double[] windowedMedian(double[] d, int n, int W) {
        double[] wmed = new double[n];
        for (int i = 0; i < n; i++) {
            int lo = Math.max(0, i - W), hi = Math.min(n - 1, i + W);
            double[] win = Arrays.stream(d, lo, hi + 1).filter(x -> !Double.isNaN(x)).sorted().toArray();
            wmed[i] = win.length > 0 ? pctlArr(win, 0.5) : Double.NaN;
        }
        return wmed;
    }

    private static double pctlArr(double[] sorted, double p) {
        if (sorted.length == 0) return Double.NaN;
        if (sorted.length == 1) return sorted[0];
        double r = Math.max(0, Math.min(1, p)) * (sorted.length - 1);
        int lo = (int) Math.floor(r), hi = (int) Math.ceil(r);
        return sorted[lo] + (r - lo) * (sorted[hi] - sorted[lo]);
    }

